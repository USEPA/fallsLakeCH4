gga_data <- gga_data %>%
  mutate(gga_row = row_number()) %>%
  left_join(
    chamber_windows,
    join_by(date_time > window_start, date_time < window_end),
    relationship = "many-to-many"
  ) %>%
  mutate(
    match_distance = abs(as.numeric(date_time - matched_deply_date_time))
  ) %>%
